"""*****III.Recurrent Neural Network model with LSTM*****"""

import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder
import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense, Dropout, Bidirectional
from tensorflow.keras.optimizers import Adam

"""*****Function to load pre-extracted MFCC features from .npy files*****"""

def load_mfcc_data(csv_file):
    X = []
    y = []

    df = pd.read_csv('/content/mfcc_data_df.csv')

    for index, row in df.iterrows():
        file_name = row['filename']
        label = row['gender']

        try:
            features = np.load(file_name)
            X.append(features)
            y.append(label)
        except Exception as e:
            print(f"Error loading {file_name}: {e}")

    X = np.array(X)
    y = np.array(y)

    return X, y

X, y = load_mfcc_data('mfcc_data.csv')

label_encoder = LabelEncoder()
y_encoded = label_encoder.fit_transform(y)

"""*****Reshape the features for LSTM input*****"""

X_reshaped = np.expand_dims(X, axis=-1)

X_train, X_test, y_train, y_test = train_test_split(X_reshaped, y_encoded, test_size=0.2, random_state=42)

"""*****create model*****"""

def create_rnn_model(input_shape):
    model = Sequential()

    model.add(Bidirectional(LSTM(128, return_sequences=False), input_shape=input_shape))
    model.add(Dropout(0.5))

    model.add(Dense(64, activation='relu'))
    model.add(Dropout(0.5))

    model.add(Dense(1, activation='sigmoid'))

    optimizer = Adam(learning_rate=0.001)
    model.compile(optimizer=optimizer, loss='binary_crossentropy', metrics=['accuracy'])

    return model

input_shape = (X_train.shape[1], 1)

model = create_rnn_model(input_shape)

history = model.fit(X_train, y_train, epochs=50, batch_size=32, validation_data=(X_test, y_test))

model.save('gender_rnn_model.h5')

test_loss, test_accuracy = model.evaluate(X_test, y_test)
print(f"Test Accuracy: {test_accuracy * 100:.2f}%")

